#!/usr/bin/env node
// Offline smoke test: open dist/index.html over file:// in headless Chromium with
// every network request blocked, fail on console errors or any network attempt,
// and save screenshots (light, dark, style sheet). Usage: node scripts/smoke.mjs [outDir]
import { chromium } from 'playwright-core';
import { resolve } from 'node:path';
import { mkdirSync } from 'node:fs';

const out = resolve(process.argv[2] || 'dist/smoke'); mkdirSync(out, { recursive: true });
const exe = process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [], requests = [];
await ctx.route('**/*', (route) => { const u = route.request().url(); if (!u.startsWith('file://')) { requests.push(u); return route.abort(); } return route.continue(); });
const page = await ctx.newPage();
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', e => errors.push(String(e)));
await page.goto('file://' + resolve('dist/index.html'));
await page.waitForSelector('.sidebar');
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: `${out}/01-welcome.png` });
await page.click('dialog .btn-primary');
await page.waitForSelector('.sg-section');
await page.screenshot({ path: `${out}/02-styleguide-light.png`, fullPage: true });
await page.click('button[aria-label="Toggle theme"]');
await page.waitForTimeout(250);
await page.screenshot({ path: `${out}/03-styleguide-dark.png`, fullPage: true });
await page.click('button[aria-label="Toggle theme"]');
await page.click('.side-nav-item:nth-child(3)');
await page.screenshot({ path: `${out}/04-run-coming-next.png` });
await page.keyboard.press('Control+K');
await page.waitForSelector('dialog.palette[open]');
await page.keyboard.type('qg2');
await page.screenshot({ path: `${out}/05-palette.png` });
await page.keyboard.press('Escape');
// Import the demo workbooks (generated on the fly), check the summary, reload and check persistence.
import { execFileSync } from 'node:child_process';
import { readdirSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
const demoDir = mkdtempSync(resolve(tmpdir(), 'fg-demo-'));
execFileSync(process.execPath, [resolve('scripts/generate-demo.mjs'), demoDir], { stdio: 'ignore' });
const demoFiles = readdirSync(demoDir).filter(f => f.endsWith('.xlsx')).map(f => resolve(demoDir, f));
await page.click('.side-nav-item:nth-child(3)');
await page.click('.tab:nth-child(2)');
await page.setInputFiles('.dropzone input[type=file]', demoFiles);
await page.waitForFunction((n) => document.querySelectorAll('.filerow .st.ok, .filerow .st.warn, .filerow .st.err').length === n, demoFiles.length, { timeout: 60000 });
await page.waitForSelector('.matrix');
await page.screenshot({ path: `${out}/06-import-summary.png`, fullPage: true });
const kpis = await page.$$eval('.kpi .value', els => els.map(e => e.textContent.trim()));
console.log('import KPIs (entities, activities, assessments, out of scope, warnings):', kpis.join(' | '));
const failed = await page.$$eval('.filerow .st.err', els => els.length);
await page.waitForFunction(() => /Saved/.test(document.querySelector('.saved')?.textContent || ''), null, { timeout: 10000 });
await page.reload();
await page.waitForSelector('.sidebar .side-stream .num');
await page.waitForFunction(() => document.querySelector('.kpi-strip .headline')?.textContent.includes('%'), null, { timeout: 10000 });
const streamCounts = await page.$$eval('.side-stream .num', els => els.map(e => e.textContent));
console.log('after reload – stream counts in sidebar:', streamCounts.join(' '));
await page.screenshot({ path: `${out}/07-after-reload.png` });
if (failed || kpis[0] !== '3' || kpis[2] !== '540' || streamCounts.includes('—')) { errors.push(`import check failed: failed=${failed} kpis=${kpis} counts=${streamCounts}`); }
// PLAN: participant + session, then workshop: bulk confirm, expand a row, edit, keyboard.
await page.click('.side-nav-item:nth-child(1)');
await page.waitForSelector('.page-head');
await page.fill('input[placeholder="e.g. Demo Group"]', 'Demo Group'); await page.press('input[placeholder="e.g. Demo Group"]', 'Enter');
await page.fill('input[placeholder="e.g. France"]', 'France'); await page.press('input[placeholder="e.g. France"]', 'Enter');
await page.fill('input[placeholder="MR"]', 'mr'); await page.press('input[placeholder="MR"]', 'Enter');
await page.fill('input[placeholder="Full name"]', 'M. Dupont'); await page.fill('input[placeholder="e.g. GL accountant"]', 'GL lead'); await page.press('input[placeholder="Full name"]', 'Enter');
await page.fill('input[type=date]', '2026-10-19'); await page.fill('input[type=time] >> nth=0', '14:00'); await page.fill('input[type=time] >> nth=1', '15:30');
await page.click('button.btn-outline:has-text("Add") >> nth=1');
await page.waitForSelector('text=Set active');
await page.click('button:has-text("Set active")');
await page.screenshot({ path: `${out}/08-plan.png`, fullPage: true });
await page.click('.side-nav-item:nth-child(3)');
await page.click('.tab:nth-child(1)');
await page.waitForSelector('.ws');
await page.click('.sessionbar .btn-primary');
await page.screenshot({ path: `${out}/09-workshop.png` });
await page.click('.l3head .btn-primary');
await page.waitForSelector('.toast');
const toastText = await page.textContent('.toast');
console.log('bulk toast:', toastText.trim());
await page.locator('.wtable tr.act td.ent').first().scrollIntoViewIfNeeded(); await page.evaluate(() => window.scrollBy(0, -250)); await page.click('.wtable tr.act td.ent .pill >> nth=0');
await page.waitForSelector('.expand-inner');
await page.click('.expand-inner .yn >> nth=0 >> button >> nth=0');
await page.selectOption('.expand-inner select >> nth=0', 'HARMONIZATION');
await page.waitForSelector('.block.dev');
await page.fill('.expand-inner input[placeholder="Short reason"]', 'Local approval by CFO'); await page.press('.expand-inner input[placeholder="Short reason"]', 'Enter');
await page.screenshot({ path: `${out}/10-workshop-expanded.png`, fullPage: true });
await page.keyboard.press('Escape');
await page.keyboard.press('ArrowDown');
await page.keyboard.press('2');
const audit = await page.evaluate(() => new Promise(res => { const r = indexedDB.open('gbs-fitgap-workbench'); r.onsuccess = () => { const g = r.result.transaction('sessions').objectStore('sessions').get('current'); g.onsuccess = () => res({ audit: g.result?.audit?.length, sessions: g.result?.sessions?.length, participants: g.result?.participants?.length }); }; }));
await page.waitForTimeout(900);
const audit2 = await page.evaluate(() => new Promise(res => { const r = indexedDB.open('gbs-fitgap-workbench'); r.onsuccess = () => { const g = r.result.transaction('sessions').objectStore('sessions').get('current'); g.onsuccess = () => res({ audit: g.result?.audit?.length, sessions: g.result?.sessions?.length, participants: g.result?.participants?.length, tagged: g.result?.audit?.filter(e => e.sessionId).length, editor: g.result?.audit?.at(-1)?.editor }); }; }));
console.log('persisted audit entries:', audit2.audit, '| tagged with session:', audit2.tagged, '| editor:', audit2.editor, '| sessions:', audit2.sessions, '| participants:', audit2.participants);
if (!(audit2.audit > 20) || audit2.sessions !== 1 || audit2.participants !== 1 || audit2.editor !== 'MR') errors.push(`workshop persistence check failed: ${JSON.stringify(audit2)}`);
const fonts = await page.evaluate(() => [...document.fonts].filter(f => f.status === 'loaded').map(f => f.family + ' ' + f.weight));
const fontsUsed = await page.evaluate(() => ({ h1: getComputedStyle(document.querySelector('h1, h2')).fontFamily, body: getComputedStyle(document.body).fontFamily }));
await browser.close();
console.log('fonts loaded:', [...new Set(fonts)].join(' | '));
console.log('h1 font:', fontsUsed.h1, '| body:', fontsUsed.body);
console.log('network attempts:', requests.length, requests.slice(0, 5));
console.log('console errors:', errors.length, errors.slice(0, 5));
console.log('screenshots in', out);
if (errors.length || requests.length) process.exit(1);
